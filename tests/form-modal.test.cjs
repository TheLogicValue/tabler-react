const assert = require('node:assert/strict')
const { test } = require('node:test')
const { createRequire } = require('node:module')
const path = require('node:path')
const consumerRequire = createRequire(path.join(process.env.TABLER_TEST_PACKAGE_DIR || path.join(__dirname, '..'), 'package.json'))
const React = consumerRequire('react')
const { renderToStaticMarkup } = consumerRequire('react-dom/server')
const { Form, FormCard, FormTextInput, FormCheckboxInput, Modal, ModalDoc, ModalSplash, Tabs, Tab } = consumerRequire(process.env.TABLER_TEST_PACKAGE_DIR || './dist/index.js')
const render = (Component, props, children) => renderToStaticMarkup(React.createElement(Component, props, children))

test('Form conserva su composición, atributos admitidos y autoComplete predeterminado en ambas versiones de React', () => {
  const html = render(Form, { action: '/save', method: 'post', className: 'consumer', id: 'ignored' }, 'Campos')
  assert.match(html, /<form class="consumer"/)
  assert.match(html, /action="\/save"/)
  assert.match(html, /method="post"/)
  assert.match(html, /autoComplete="off"/)
  assert.doesNotMatch(html, /ignored/)
  assert.match(render(Form, { autoComplete: 'on' }), /autoComplete="on"/)
  const input = render(Form.Input, { defaultValue: 'Hola', name: 'name', icon: 'search', position: 'append', error: 'Revisar' })
  assert.match(input, /^<div class="input-icon"><input\b/)
  for (const attribute of ['class="form-control is-invalid state-invalid"', 'type="text"', 'name="name"', 'value="Hola"']) assert.ok(input.includes(attribute))
  assert.match(input, /<span class="input-icon-addon"><i class="fe fe-search"><\/i><\/span><\/div><span class="invalid-feedback">Revisar<\/span>$/)
  const group = render(Form.Group, { label: 'Importe', isRequired: true, inputProps: { defaultValue: 4 }, labelLeft: true }, 'Ignorado')
  assert.match(group, /class="row row mb-5"/)
  assert.match(group, /Importe<span class="form-required">\*<\/span>/)
  assert.match(group, /value="4"/)
  assert.doesNotMatch(group, /Ignorado/)
})

test('Los campos agrupados conservan tipos, clases y opciones de composición', () => {
  const children = ['a', 'b'].map(value => React.createElement(Form.SelectGroupItem, { key: value, name: 'letters', value, label: value }))
  const group = render(Form.SelectGroup, { canSelectMultiple: true, pills: true }, children)
  assert.equal([...group.matchAll(/type="checkbox"/g)].length, 2)
  assert.match(group, /selectgroup-pills/)
  assert.equal(render(Form.InputGroup, { prepend: true }, 'Antes'), '<span class="input-group-prepend">Antes</span>')
  assert.equal(render(Form.InputGroup, { append: true }, 'Después'), '<span class="input-group-append">Después</span>')
  const range = render(Form.Ratio, { defaultValue: 3, min: 0, max: 10 })
  assert.equal([...range.matchAll(/value="3"/g)].length, 2)
  assert.match(range, /type="range"/)
  assert.match(range, /type="number"[^>]*readonly=""/i)
  const select = render(Form.Select, { multiple: true, value: ['a'], onChange: () => undefined }, React.createElement('option', { value: 'a' }, 'A'))
  assert.match(select, /multiple=""/)
  assert.match(select, /value="a" selected=""/)
})

test('Form.DatePicker conserva formato, fecha y límites mediante los tres selectores controlados', () => {
  const html = render(Form.DatePicker, { defaultDate: new Date(Date.UTC(2026, 9, 15, 12)), minYear: 2025, maxYear: 2026, format: 'dd/mm/yyyy' })
  assert.equal([...html.matchAll(/<select\b/g)].length, 3)
  assert.ok(html.indexOf('value="15" selected=""') < html.indexOf('>October<'))
  assert.match(html, /value="9" selected="">October/)
  assert.match(html, /value="2026" selected="">2026/)
  assert.doesNotMatch(html, /value="2024"/)
})

test('Los wrappers de formulario mantienen las etiquetas, campos y envío explícito', () => {
  const html = render(FormCard, { title: 'Acceso', buttonText: 'Entrar' }, [
    React.createElement(FormTextInput, { key: 'name', name: 'name', label: 'Nombre', defaultValue: 'Ana' }),
    React.createElement(FormCheckboxInput, { key: 'terms', label: 'Acepto', name: 'terms' }),
  ])
  assert.match(html, /<form class="card"/)
  assert.match(html, /<div class="card-title">Acceso<\/div>/)
  assert.match(html, /<label class="form-label">Nombre<\/label>/)
  assert.match(html, /class="custom-control-label">Acepto/)
  assert.match(html, /type="submit">Entrar<\/button>/)
})

test('Modal conserva estados, acciones, visibilidad y tamaños; ModalDoc admite un documento vacío', () => {
  const html = render(Modal, { type: 3, title: 'Confirmar', modalLG: true, bodyHeight: 200 }, 'Contenido')
  assert.match(html, /modal modal-blur fade show/)
  assert.match(html, /modal-dialog modal-lg modal-dialog-centered/)
  assert.match(html, /height:200px/)
  assert.match(html, /Leave Page/)
  const buttons = [...html.matchAll(/<button\b[^>]*>/g)]
  assert.equal(buttons.length, 4)
  assert.ok(buttons.every(match => match[0].includes('type="button"')))
  const loading = render(Modal, { body: 'load' }, 'Texto')
  assert.match(loading, /modal-load/)
  assert.doesNotMatch(loading, /<button/)
  assert.match(loading, /Texto/)
  assert.doesNotMatch(render(Modal, { noFooter: true, show: false }), /modal-footer|fade show/)
  assert.match(render(Modal, { body: 'error' }), /loader-svg error/)
  assert.match(render(Modal, { body: 'ok' }), /loader-svg success/)
  assert.match(render(ModalDoc, { items: [{ title: 'Oculta', value: 'features' }], pathname: '/other' }), /modal-body/)
  assert.match(render(ModalSplash, { image: '/logo.svg' }).replace(/^<link\b[^>]*>/, ''), /alt="splash"/)
})

test('Tabs mantiene la selección inicial y Tab conserva su raíz e ignora style', () => {
  const html = render(Tabs, { initialTab: 'Uno', options: 'Acción' }, [React.createElement(Tab, { key: '1', title: 'Uno' }, 'Contenido uno'), React.createElement(Tab, { key: '2', title: 'Dos' }, 'Contenido dos')])
  assert.match(html, /Contenido uno/)
  assert.doesNotMatch(html, /Contenido dos/)
  assert.match(html, /Acción/)
  assert.equal(render(Tab, { title: 'Uno', style: { padding: 0 } }, 'Panel'), '<div class="card-body">Panel</div>')
  assert.doesNotMatch(render(Tabs, {}, React.createElement(Tab, { title: 'Uno' }, 'Sin selección')), /Sin selección/)
})
